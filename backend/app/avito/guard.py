"""Проверка ответа бота перед отправкой: запрещённые слова, обещания и контакты.

Нарушение = брак: такой ответ не уходит клиенту. Бот получает замечание и пишет заново;
если и вторая попытка с нарушением — ответ не отправляется, директору уходит алерт.
Только стандартная библиотека.
"""
import re

RULES: list[tuple[str, re.Pattern]] = [
    ("телефон", re.compile(r"(\+7|\b8)[\s\-()]*\d{3}[\s\-()]*\d{3}[\s\-]*\d{2}[\s\-]*\d{2}")),
    ("ссылка", re.compile(r"https?://|www\.|\b[\w-]+\.(ru|рф|com|net|org|su|pro)\b", re.I)),
    ("e-mail", re.compile(r"[\w.+-]+@[\w-]+\.\w+")),
    ("слово «трассировка»", re.compile(r"трассировк", re.I)),
    ("группа по электробезопасности", re.compile(r"электробезопасност|\b[IV]{1,3}\s*групп|групп\w*\s+допуск", re.I)),
    ("число выполненных объектов", re.compile(r"\b\d+\s+(выполненн\w+\s+)?(объект\w*|квартир\w*)\s+(за\s+плечами|выполнен|сдан|сделан)|\b53\s+объект", re.I)),
    ("«схема скрытых трасс»", re.compile(r"схем\w*\s+скрыт", re.I)),
    ("лицензии, СРО, допуски", re.compile(r"лиценз|\bСРО\b|допуск", re.I)),
    ("срок «за N дней»", re.compile(r"\bза\s+\d+[\s\-–]*(дн|дня|дней|день)", re.I)),
    ("«без предоплаты»", re.compile(r"без\s+предоплат", re.I)),
    ("скидки", re.compile(r"скидк", re.I)),
    ("«24/7», круглосуточно", re.compile(r"24\s*/\s*7|круглосуточ", re.I)),
    # «рассчитаем за 30 минут» можно (подтверждено руководителем 14.10.2026), «приедем за 30 минут» — нет
    ("«выезд за 30 минут»", re.compile(r"(выезд\w*|выед\w*|приед\w*|приезж\w*|будем у вас|подъед\w*)[^.?!]{0,30}за\s+\d+\s*мин", re.I)),
]


def violations(text: str) -> list[str]:
    return [name for name, rx in RULES if rx.search(text or "")]
