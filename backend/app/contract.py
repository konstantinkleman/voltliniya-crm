def num_fmt(v) -> str:
    return f"{v:,.2f}".replace(",", " ").replace(".", ",")


def qty_fmt(v) -> str:
    if abs(v - round(v)) < 1e-9:
        return str(int(round(v)))
    return f"{v:.2f}".rstrip("0").rstrip(".").replace(".", ",")


def line_sum(x) -> float:
    return round(x["qty"] * x["price"], 2)


